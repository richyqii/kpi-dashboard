const {test,expect}=require('@playwright/test');
const {resetBaseline,upload,post}=require('./api-helpers.cjs');
test('Use This Version applies directly and preserves history without review steps',async({page})=>{
 await resetBaseline(page.request);
 const preview=await upload(page.request,'KPI Status 22.10.2026.xlsx');
 const draft=await preview.json();
 expect(preview.ok()).toBe(true);
 const saved=await post(page.request,'/api/commit',{draftId:draft.id,approved:true,useUploadedFile:true});
 expect(saved.ok()).toBe(true);
 const before=await(await page.request.get('/api/versions')).json();
 await page.goto('/');await expect(page.locator('#excelUpload')).toBeEnabled();
 let release;const gate=new Promise(resolve=>release=resolve);let calls=0;
 await page.route('**/api/use-version',async route=>{calls++;await gate;await route.continue();});
 await page.route('**/api/rollback-preview',()=>{throw new Error('Review must not be requested');});
 await page.locator('#versionHistory').click();
 const target=page.locator('.workflow-version').filter({hasText:'baseline'}).filter({has:page.getByRole('button',{name:'Use This Version',exact:true})}).first();
 await target.getByRole('button',{name:'Use This Version',exact:true}).click();
 await expect(page.locator('#workflowTitle')).toHaveText('Making changes...');
 await expect(page.locator('#workflowSteps')).toBeHidden();
 await page.keyboard.press('Escape');await expect(page.locator('#uploadWorkflow')).toBeVisible();
 release();await expect(page.locator('#workflowTitle')).toHaveText('Update Successful');
 expect(calls).toBe(1);
 const after=await(await page.request.get('/api/versions')).json();
 expect(after.currentId).toBe('initial-baseline');
 expect(after.versions.map(v=>v.id)).toEqual(before.versions.map(v=>v.id));
 await page.getByRole('button',{name:'Done',exact:true}).click();await page.reload();
 await expect(page.locator('#excelUpload')).toBeEnabled();
 expect((await(await page.request.get('/api/current')).json()).version.id).toBe('initial-baseline');
});
